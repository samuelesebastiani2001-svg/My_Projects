T(6) = y(10)^params(9);
T(7) = params(10)*y(6)^params(7);
T(8) = (y(11)/y(15))^params(8);
T(9) = T(7)*T(8);
T(10) = T(9)^(1-params(9));
T(11) = params(17)*y(13)^params(5);
T(12) = y(12)^params(2);
lhs(1) = 1;
rhs(1) = params(1)*y(10)*1/y(6);
lhs(2) = y(3);
rhs(2) = T(1)*T(2);
lhs(3) = y(1);
rhs(3) = y(2)*y(16)/y(4);
lhs(4) = y(11);
rhs(4) = y(1);
lhs(5) = y(5);
rhs(5) = params(3)/(params(3)-1)*y(8)/y(9);
lhs(6) = y(8);
rhs(6) = y(1)*y(7)+y(8)*params(1)*params(4)*T(3);
lhs(7) = y(9);
rhs(7) = y(1)+y(9)*T(4);
lhs(8) = y(4);
rhs(8) = y(4)*params(4)*T(3)+(1-params(4))*y(5)^(-params(3));
lhs(9) = y(6);
rhs(9) = T(5)^(1/(params(3)-1));
lhs(10) = y(7);
rhs(10) = y(3)*(1-params(6))/y(16);
