lhs = NaN(19, 1);
rhs = NaN(19, 1);
T(1) = params(17)*y(2)^params(5);
T(2) = y(1)^params(2);
T(3) = y(6)^params(3);
T(4) = params(1)*params(4)*y(6)^(params(3)-1);
