lhs(15) = y(15);
rhs(15) = y(12);
lhs(16) = y(19);
rhs(16) = y(11)/y(15);
lhs(17) = log(y(16));
rhs(17) = log(y(16))*params(11)+params(12)*x(1);
lhs(18) = y(17);
rhs(18) = y(17)*params(13)+params(14)*x(2);
lhs(19) = y(18);
rhs(19) = y(18)*params(15)+params(16)*x(3);
end
