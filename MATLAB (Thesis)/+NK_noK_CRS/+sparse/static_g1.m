function [g1, T_order, T] = static_g1(y, x, params, sparse_rowval, sparse_colval, sparse_colptr, T_order, T)
if nargin < 8
    T_order = -1;
    T = NaN(15, 1);
end
[T_order, T] = NK_noK_CRS.sparse.static_g1_tt(y, x, params, T_order, T);
g1_v = NaN(50, 1);
g1_v(1)=(-(T(1)*getPowerDeriv(y(1),params(2),1)));
g1_v(2)=1;
g1_v(3)=(-1);
g1_v(4)=(-y(7));
g1_v(5)=(-1);
g1_v(6)=(-(T(2)*params(17)*getPowerDeriv(y(2),params(5),1)));
g1_v(7)=(-(y(16)/y(4)));
g1_v(8)=1;
g1_v(9)=(-((1-params(6))/y(16)));
g1_v(10)=(-(y(2)*(-y(16))/(y(4)*y(4))));
g1_v(11)=1-params(4)*T(3);
g1_v(12)=1;
g1_v(13)=(-((1-params(4))*getPowerDeriv(y(5),(-params(3)),1)));
g1_v(14)=(-((-((1-params(4))*getPowerDeriv(y(5),1-params(3),1)))/params(4)*getPowerDeriv(T(5),1/(params(3)-1),1)));
g1_v(15)=(-(params(1)*y(10)*(-1)/(y(6)*y(6))));
g1_v(16)=(-(y(8)*params(1)*params(4)*T(13)));
g1_v(17)=(-(y(9)*params(1)*params(4)*getPowerDeriv(y(6),params(3)-1,1)));
g1_v(18)=(-(y(4)*params(4)*T(13)));
g1_v(19)=1;
g1_v(20)=(-(exp(y(18))*T(6)*T(8)*params(10)*getPowerDeriv(y(6),params(7),1)*T(14)));
g1_v(21)=(-y(1));
g1_v(22)=1;
g1_v(23)=(-(params(3)/(params(3)-1)*1/y(9)));
g1_v(24)=1-params(1)*params(4)*T(3);
g1_v(25)=(-(params(3)/(params(3)-1)*(-y(8))/(y(9)*y(9))));
g1_v(26)=1-T(4);
g1_v(27)=(-(params(1)*1/y(6)));
g1_v(28)=1-exp(y(18))*T(10)*getPowerDeriv(y(10),params(9),1);
g1_v(29)=1;
g1_v(30)=(-(exp(y(18))*T(6)*T(14)*T(7)*1/y(15)*T(15)));
g1_v(31)=(-(1/y(15)));
g1_v(32)=(-(T(11)*getPowerDeriv(y(12),params(2),1)));
g1_v(33)=1;
g1_v(34)=(-1);
g1_v(35)=(-(T(12)*params(17)*getPowerDeriv(y(13),params(5),1)));
g1_v(36)=(-y(16));
g1_v(37)=1;
g1_v(38)=(-(1-params(6)));
g1_v(39)=(-(exp(y(18))*T(6)*T(14)*T(7)*T(15)*(-y(11))/(y(15)*y(15))));
g1_v(40)=1;
g1_v(41)=(-((-y(11))/(y(15)*y(15))));
g1_v(42)=(-(y(2)*1/y(4)));
g1_v(43)=(-((-(y(3)*(1-params(6))))/(y(16)*y(16))));
g1_v(44)=(-y(13));
g1_v(45)=(params(3)-1)/params(3);
g1_v(46)=1/y(16)-params(11)*1/y(16);
g1_v(47)=1-params(13);
g1_v(48)=(-(T(6)*T(10)*exp(y(18))));
g1_v(49)=1-params(15);
g1_v(50)=1;
if ~isoctave && matlab_ver_less_than('9.8')
    sparse_rowval = double(sparse_rowval);
    sparse_colval = double(sparse_colval);
end
g1 = sparse(sparse_rowval, sparse_colval, g1_v, 19, 19);
end
